import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { tmpdir } from 'node:os';
import { root, run, silk } from '../../scripts/internal.mjs';

const options = new Set(process.argv.slice(2));
for (const option of options) if (!['--fetch', '--update', '--check'].includes(option)) throw new Error(`Unknown option: ${option}`);
if (options.has('--fetch') && options.has('--update')) throw new Error('Choose --fetch or --update');
if (options.has('--update') && options.has('--check')) throw new Error('Choose --update or --check');
const update = options.has('--update');
const lockPath = resolve(root, 'svg/idna.lock.json');
const cache = resolve(root, 'svg/.cache/idna');
const output = resolve(root, 'svg/src/url_idna_data.silk');
const urls = { mapping: 'https://www.unicode.org/Public/18.0.0/idna/IdnaMappingTable.txt', license: 'https://www.unicode.org/license.txt' };
const lock = update ? {} : JSON.parse(readFileSync(lockPath, 'utf8'));
if (!update && (lock.format !== 1 || lock.unicode !== '18.0.0' || Object.keys(lock.sources).sort().join() !== Object.keys(urls).sort().join())) throw new Error('Invalid IDNA lock');
const sources = {}, records = {};
for (const name of Object.keys(urls)) {
  let record = lock.sources?.[name];
  let bytes;
  if (!update && existsSync(resolve(cache, record.sha256))) bytes = readFileSync(resolve(cache, record.sha256));
  else {
    if (!update && !options.has('--fetch')) throw new Error(`Missing ${name} cache; use --fetch`);
    const response = await fetch(update ? urls[name] : record.resolved, { signal: AbortSignal.timeout(90000) });
    if (!response.ok) throw new Error(`IDNA download failed: ${response.status}`);
    bytes = Buffer.from(await response.arrayBuffer());
    if (update) record = { url: urls[name], resolved: response.url, sha256: createHash('sha256').update(bytes).digest('hex') };
  }
  if (createHash('sha256').update(bytes).digest('hex') !== record.sha256) throw new Error(`${name}: pinned digest mismatch`);
  mkdirSync(cache, { recursive: true });
  writeFileSync(resolve(cache, record.sha256), bytes);
  sources[name] = new TextDecoder('utf-8', { fatal: true }).decode(bytes);
  records[name] = record;
}
if (!sources.mapping.includes('# Version: 18.0.0')) throw new Error('Mapping must match Unicode 18.0.0');
const status = { valid: 0, deviation: 1, ignored: 2, mapped: 3, disallowed: 4 };
const rows = [], pool = [], mappings = new Map();
const packed = value => [value & 255, (value >>> 8) & 255, (value >>> 16) & 255];
let next = 0;
for (const line of sources.mapping.split(/\r?\n/)) {
  const fields = line.split('#', 1)[0].split(';').map(part => part.trim());
  if (!fields[0]) continue;
  const bounds = fields[0].split('..').map(value => parseInt(value, 16));
  if (bounds[0] !== next) throw new Error('Mapping ranges must cover Unicode contiguously');
  next = bounds.at(-1) + 1;
  const kind = status[fields[1]];
  if (kind === undefined) throw new Error(`Unknown IDNA status: ${fields[1]}`);
  const mapping = kind === 3 && fields[2] ? fields[2].split(/\s+/).map(value => parseInt(value, 16)) : [];
  const key = mapping.join(',');
  if (!mappings.has(key)) { mappings.set(key, pool.length / 3); for (const cp of mapping) pool.push(...packed(cp)); }
  if (mapping.length > 255) throw new Error('Mapping exceeds packed length');
  rows.push(...packed(bounds[0]), kind, ...packed(mappings.get(key)), mapping.length);
}
if (next !== 0x110000) throw new Error('Incomplete mapping');
const literal = (name, bytes) => `fn ${name}() -> &'static [u8] {\n  return b"${bytes.map(byte => '\\x' + byte.toString(16).padStart(2, '0')).join('')}"\n}\n`;
let result = '// Generated by svg/scripts/generate-idna. DO NOT EDIT.\n// Unicode18.0.0 UTS46; source hashes: svg/idna.lock.json.\n';
result += sources.license.replace(/\r?\n$/, '').split(/\r?\n/).map(line => '// ' + line).join('\n') + '\n';
result += 'import silk.num.u8\nimport silk.num.u32\n\n' + literal('records', rows) + '\n' + literal('mappings', pool);
result += `
fn word(bytes: &[u8], at: usize) -> u32 {
  return u8.toU32(bytes[at]) | u32.shiftLeft(u8.toU32(bytes[at + 1]), 8)
    | u32.shiftLeft(u8.toU32(bytes[at + 2]), 16)
}

// Returns a record offset; all scalar slots including unassigned are covered.
pub fn lookup(cp: u32) -> usize {
  let data = records()
  let mut low: usize = 0
  let mut high = data.length / 8
  while low + 1 < high {
    let middle = low + (high - low) / 2
    if word(data, middle * 8) <= cp { low = middle } else { high = middle }
  }
  return low * 8
}

pub fn status(record: usize) -> u8 { return records()[record + 3] }
pub fn length(record: usize) -> usize { return u8.toUsize(records()[record + 7]) }
pub fn mapping(record: usize, index: usize) -> u32 {
  return word(mappings(), (u32.toUsize(word(records(), record + 4)) + index) * 3)
}
`;
const staging = mkdtempSync(resolve(tmpdir(), 'svg-idna-'));
try {
  const path = resolve(staging, 'url_idna_data.silk');
  writeFileSync(path, result);
  run(silk, ['format', path]);
  const formatted = readFileSync(path);
  if (options.has('--check')) {
    if (!existsSync(output) || !readFileSync(output).equals(formatted)) throw new Error('Generated IDNA table differs; run node svg/scripts/generate-idna --fetch');
  } else if (!existsSync(output) || !readFileSync(output).equals(formatted)) writeFileSync(output, formatted);
} finally { rmSync(staging, { recursive: true, force: true }); }
if (update) writeFileSync(lockPath, JSON.stringify({ format: 1, unicode: '18.0.0', license: 'Unicode-3.0', sources: records }, null, 2) + '\n');
console.log(`Materialized ${rows.length / 8} mapping records, ${pool.length / 3} mapping scalars`);
